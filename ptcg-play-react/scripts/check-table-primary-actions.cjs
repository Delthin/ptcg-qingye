// Focused source-level ownership checks. No network, database, browser or emitted files.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/table/hud/TablePrimaryActionStore.ts'), 'utf8');
const moduleResult = { exports: {} };
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText;
new Function('exports', 'module', js)(moduleResult.exports, moduleResult);
const { TablePrimaryActionStore } = moduleResult.exports;
const store = new TablePrimaryActionStore();
const host = {};
const calls = [];
const endTurn = () => calls.push('end-turn');
const cancelHandPlay = () => calls.push('cancel-hand-play');
const confirmPrompt = () => calls.push('confirm-prompt');
const cancelPrompt = () => calls.push('cancel-prompt');
const base = { host, active: true, disabled: false, state: 'ready' };
let publications = 0;
const unsubscribe = store.subscribe(() => publications++);
assert.equal(store.getSnapshot(), null);
store.set('board', { ...base, priority: 10, label: '结束回合', onActivate: endTurn, onCancel: cancelHandPlay });
store.set('prompt', { ...base, priority: 100, label: '确认', onActivate: confirmPrompt, onCancel: cancelPrompt });
assert.equal(store.getSnapshot().id, 'prompt');
store.getSnapshot().onCancel();
assert.deepEqual(calls, ['cancel-prompt'], 'A prompt cancellation must not use the underlying board callback');
store.set('board', { ...base, priority: 10, label: '结束回合', onActivate: endTurn, onCancel: cancelHandPlay });
assert.equal(store.getSnapshot().onActivate, confirmPrompt);
assert.equal(store.getSnapshot().onCancel, cancelPrompt, 'A board rerender must not replace either prompt action');
store.set('prompt', { ...base, priority: 100, label: '确认', onActivate: confirmPrompt });
assert.equal(store.getSnapshot().onCancel, undefined, 'A non-cancellable prompt must not inherit the board cancellation');
store.set('prompt', { ...base, priority: 100, label: '选择选项', state: 'choose', disabled: true, onCancel: cancelPrompt });
assert.equal(store.getSnapshot().onActivate, undefined, 'Direct-choice prompts must block the underlying end-turn action');
assert.equal(store.getSnapshot().onCancel, cancelPrompt, 'Cancellation remains registered when confirmation is not available');
store.remove('prompt');
assert.equal(store.getSnapshot().id, 'board');
assert.equal(store.getSnapshot().onActivate, endTurn);
assert.equal(store.getSnapshot().onCancel, cancelHandPlay);
store.remove('board');
assert.equal(store.getSnapshot(), null, 'Unmounting the final owner must clear both actions');
const beforeUnsubscribe = publications;
unsubscribe();
store.set('board', { ...base, priority: 10, label: '结束回合', onActivate: endTurn });
assert.equal(publications, beforeUnsubscribe);
assert.ok(publications >= 6);
console.log('PASS: paired ownership, prompt priority, non-cancellable/direct-choice prompts, cleanup and subscription');
